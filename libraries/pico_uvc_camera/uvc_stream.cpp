#include <cstring>

#include "uvc_stream.h"

namespace
{
    constexpr uint8_t HEADER_FID = 0x01;
    constexpr uint8_t HEADER_EOF = 0x02;
    constexpr uint8_t HEADER_ERR = 0x40;
}

void UvcFrameAssembler::set_buffer(uint8_t *buffer, uint32_t capacity)
{
    m_buffer = buffer;
    m_capacity = capacity;
    reset();
}

void UvcFrameAssembler::replace_buffer(uint8_t *buffer, uint32_t capacity)
{
    m_buffer = buffer;
    m_capacity = capacity;
    m_copying = false;
    m_done = false;
    m_size = 0;
}

void UvcFrameAssembler::arm()
{
    if (!m_done)
    {
        m_armed = true;
    }
}

void UvcFrameAssembler::disarm()
{
    m_armed = false;
    m_copying = false;
}

void UvcFrameAssembler::reset()
{
    m_armed = false;
    m_done = false;
    m_copying = false;
    m_damaged = false;
    m_overflow = false;
    m_at_start = false;
    m_fid = -1;
    m_size = 0;
    m_frame_bytes = 0;
}

void UvcFrameAssembler::on_iso_packet(const uint8_t *data, uint32_t len, bool ok)
{
    ++m_stats.packets;

    if (!ok)
    {
        ++m_stats.bad_packets;
        m_damaged = m_damaged || m_copying;
        return;
    }

    if (len == 0)
    {
        ++m_stats.empty_packets;
        return;
    }

    uint8_t header_len = data[0];

    if ((header_len < 2) || (header_len > len))
    {
        ++m_stats.bad_packets;
        m_damaged = m_damaged || m_copying;
        return;
    }

    uint8_t info = data[1];
    int fid = info & HEADER_FID;
    const uint8_t *payload = data + header_len;
    uint32_t payload_len = len - header_len;

    m_stats.bytes += payload_len;

    if ((m_fid >= 0) && (fid != m_fid) && !m_at_start)
    {
        end_of_frame();
    }
    m_fid = fid;

    bool eof = (info & HEADER_EOF) != 0;

    if (m_at_start && ((payload_len > 0) || eof))
    {
        m_at_start = false;

        if (m_armed && !m_done && (m_buffer != nullptr))
        {
            m_copying = true;
            m_damaged = false;
            m_overflow = false;
            m_size = 0;
        }
    }

    m_frame_bytes += payload_len;

    if (m_copying)
    {
        if (info & HEADER_ERR)
        {
            m_damaged = true;
        }

        if (payload_len > 0)
        {
            if (m_size + payload_len > m_capacity)
            {
                m_overflow = true;
            }
            else if (!m_overflow)
            {
                memcpy(m_buffer + m_size, payload, payload_len);
                m_size += payload_len;
            }
        }
    }

    if (eof)
    {
        end_of_frame();
    }
}

void UvcFrameAssembler::end_of_frame()
{
    if (m_copying)
    {
        finish();
    }
    ++m_stats.frames_seen;
    m_at_start = true;

    if (m_frame_bytes > 0)
    {
        ++m_measured_frames;
        if (m_frame_bytes > m_measured_largest)
        {
            m_measured_largest = m_frame_bytes;
        }
    }
    m_frame_bytes = 0;
}

void UvcFrameAssembler::finish()
{
    m_copying = false;

    if (m_size > m_stats.largest_frame)
    {
        m_stats.largest_frame = m_size;
    }

    if (m_overflow)
    {
        ++m_stats.dropped_overflow;
        m_size = 0;
        return;
    }

    if (m_damaged)
    {
        ++m_stats.dropped_error;
        m_size = 0;
        return;
    }

    uint32_t trimmed = 0;
    while ((m_size > 4) && (m_buffer[m_size - 1] == 0) && (trimmed < 64))
    {
        --m_size;
        ++trimmed;
    }

    bool valid = (m_size >= 4) &&
                 (m_buffer[0] == 0xff) && (m_buffer[1] == 0xd8) &&
                 (m_buffer[m_size - 2] == 0xff) && (m_buffer[m_size - 1] == 0xd9);

    if (!valid)
    {
        ++m_stats.dropped_invalid;
        m_size = 0;
        return;
    }

    ++m_stats.frames_taken;
    m_done = true;
    m_armed = false;
}

uint32_t uvc_jpeg_dht_insert_offset(const uint8_t *jpeg, uint32_t len)
{
    if ((len < 4) || (jpeg[0] != 0xff) || (jpeg[1] != 0xd8))
    {
        return 0;
    }

    uint32_t pos = 2;
    while (pos + 4 <= len)
    {
        if (jpeg[pos] != 0xff)
        {
            return 0;
        }

        uint8_t marker = jpeg[pos + 1];

        if (marker == 0xff)
        {
            ++pos;
            continue;
        }
        if (marker == 0xc4)
        {
            return 0;
        }
        if (marker == 0xda)
        {
            return pos;
        }

        uint32_t segment = ((uint32_t)jpeg[pos + 2] << 8) | jpeg[pos + 3];
        pos += 2 + segment;
    }

    return 0;
}

